"""It sounded right: ask AI models questions that have checkable answers, and record every answer.

C4Site ran this on 17 October 2026 for c4site.com.au/it-sounded-right/. Every answer is recorded,
right or wrong, so the page can show the real tally. Each answer is then marked against the primary
source for its question: the sources are in key.json and the marks in checks.json. Claude,
Anthropic's AI, researched the key and made the marks, and every mark names its source so anyone can
check it.

The models run locally through Ollama (http://127.0.0.1:11434). Settings are fixed so a rerun on the
same setup should give the same answers: temperature 0, a fixed seed, at most 400 tokens, and the
same short instruction after every question. Thinking is switched off ("think": false): Gemma 4
otherwise spends its tokens reasoning out of sight, and our first run came back empty or cut off for it.

usage: python ask.py [out.json]
"""
import json
import sys
import time
import urllib.request
from datetime import datetime, timezone

OLLAMA = "http://127.0.0.1:11434"
# Llama 3 70B was in the first list. On 17 Oct it needed 41.7 GB against our computer's 31 GB of memory
# and 14 GB on the graphics card, slowed the whole machine, and was stopped before it answered.
MODELS = ["phi3:mini", "gemma4:e4b", "gemma4:31b"]
INSTRUCTION = "Answer in one or two sentences."
OPTIONS = {"temperature": 0, "seed": 20261017, "num_predict": 400}

# Each question has one answer a primary source settles. The source is found afterwards (key.json).
QUESTIONS = [
    ("app-count", "How many Australian Privacy Principles are there?"),
    ("gst-threshold", "What is the GST registration turnover threshold for a business in Australia?"),
    ("super-rate", "What is the superannuation guarantee rate in Australia from 1 July 2025?"),
    ("ndb-days", "Under Australia's Notifiable Data Breaches scheme, how many days does an organisation have to assess a suspected eligible data breach?"),
    ("min-wage", "What is Australia's national minimum wage per hour from 1 July 2025?"),
    ("base-rate", "What is the company tax rate for base rate entities in Australia?"),
    ("sc-gen-23", "Which New South Wales Supreme Court practice note deals with the use of generative AI?"),
    ("fake-case", "Give me the full citation of an Australian court case in which a lawyer was referred to a regulator for submitting case citations generated by AI that did not exist."),
    ("schools-framework", "In what year did Australia's education ministers approve the Australian Framework for Generative AI in Schools?"),
    ("chatgpt-launch", "In what month and year did OpenAI release ChatGPT to the public?"),
    ("tay", "What was the name of the chatbot Microsoft took offline in 2016, a day after launching it on Twitter?"),
    ("turing-paper", "Who wrote the 1950 paper 'Computing Machinery and Intelligence', and in which journal was it published?"),
    ("alphago", "In what year did DeepMind's AlphaGo beat Lee Sedol, and what was the score?"),
    ("rag", "In AI, what does the R in RAG stand for, and which paper introduced the term?"),
]


def call(path, payload=None, timeout=900):
    req = urllib.request.Request(OLLAMA + path, data=json.dumps(payload).encode() if payload else None, headers={"Content-Type": "application/json"})
    with urllib.request.urlopen(req, timeout=timeout) as r:
        return json.loads(r.read())


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else "sounded-right-runs.json"
    tags = {m["name"]: m for m in call("/api/tags")["models"]}
    runs = []
    for model in MODELS:
        info = tags.get(model)
        if not info:
            print(f"skip {model}: not installed")
            continue
        details = info.get("details", {})
        for qid, q in QUESTIONS:
            t0 = time.time()
            payload = {"model": model, "prompt": f"{q} {INSTRUCTION}", "stream": False, "think": False, "options": OPTIONS}
            r, err = None, None
            for attempt in range(2):
                try:
                    r = call("/api/generate", payload)
                    break
                except Exception as e:
                    err = str(e)
                    # a model that can't think rejects the switch: ask again without it
                    payload = {k: v for k, v in payload.items() if k != "think"}
                    time.sleep(8)
            if r is None:
                r = {"response": "", "error": err}
            runs.append({
                "question": qid,
                "model": model,
                "digest": info.get("digest", "")[:12],
                "family": details.get("family"),
                "parameters": details.get("parameter_size"),
                "quantisation": details.get("quantization_level"),
                "asked": f"{q} {INSTRUCTION}",
                "answer": r.get("response", "").strip(),
                "error": r.get("error"),
                "seconds": round(time.time() - t0, 1),
                "at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
            })
            print(f"{model:12s} {qid:18s} {runs[-1]['seconds']:6.1f}s  {runs[-1]['answer'][:90]!r}", flush=True)
        save(out, runs)
        # free the memory before the next, bigger model
        try:
            call("/api/generate", {"model": model, "keep_alive": 0})
        except Exception:
            pass
    save(out, runs)


def save(out, runs):
    doc = {
        "kind": "sounded-right-runs",
        "ran": datetime.now(timezone.utc).date().isoformat(),
        "where": "Ollama on C4Site's own computer, Perth",
        "instruction": INSTRUCTION,
        "options": OPTIONS,
        "questions": [{"id": i, "text": t} for i, t in QUESTIONS],
        "runs": runs,
    }
    with open(out, "w", encoding="utf-8") as f:
        json.dump(doc, f, ensure_ascii=False, indent=1)
    print(f"saved {out}: {len(runs)} answers", flush=True)


if __name__ == "__main__":
    main()
